/**
 * Packs the `remcraft-flashcards` Claude skill (`skills/remcraft-flashcards/`)
 * into `public/remcraft-flashcards.zip`, which the app offers for download
 * ("Claude-Skill" on a slide deck). Runs before `dev` and `build`, so the
 * download always matches the skill in the repository.
 *
 * Writes a plain ZIP (stored, no compression) with the skill folder as the
 * top-level directory - the layout Claude expects when uploading a skill.
 * No dependencies: the ZIP format is simple enough to write directly.
 */
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const skillDir = join(root, 'skills', 'remcraft-flashcards');
const out = join(root, 'public', 'remcraft-flashcards.zip');

/** CRC-32 lookup table (polynomial 0xEDB88320). */
const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});

/** CRC-32 of a buffer. */
function crc32(buf) {
  let c = 0xffffffff;
  for (const byte of buf) c = CRC_TABLE[(c ^ byte) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

/** All files below a directory (sorted, skipping caches). */
function listFiles(dir) {
  return readdirSync(dir)
    .filter((name) => name !== '__pycache__' && !name.startsWith('.'))
    .sort()
    .flatMap((name) => {
      const path = join(dir, name);
      return statSync(path).isDirectory() ? listFiles(path) : [path];
    });
}

/** Builds the ZIP archive. */
function zip(files) {
  const locals = [];
  const centrals = [];
  let offset = 0;
  // Fixed timestamp (1 Jan 2026) keeps the archive byte-identical between builds.
  const dosTime = 0;
  const dosDate = ((2026 - 1980) << 9) | (1 << 5) | 1;
  for (const { name, data } of files) {
    const nameBuf = Buffer.from(name, 'utf8');
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4); // version needed
    local.writeUInt16LE(0x0800, 6); // UTF-8 names
    local.writeUInt16LE(0, 8); // stored
    local.writeUInt16LE(dosTime, 10);
    local.writeUInt16LE(dosDate, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(data.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBuf.length, 26);
    local.writeUInt16LE(0, 28);
    locals.push(local, nameBuf, data);

    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4); // version made by
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0x0800, 8);
    central.writeUInt16LE(0, 10);
    central.writeUInt16LE(dosTime, 12);
    central.writeUInt16LE(dosDate, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(data.length, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(nameBuf.length, 28);
    central.writeUInt32LE(offset, 42);
    centrals.push(central, nameBuf);
    offset += local.length + nameBuf.length + data.length;
  }
  const centralSize = centrals.reduce((n, b) => n + b.length, 0);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(files.length, 8);
  end.writeUInt16LE(files.length, 10);
  end.writeUInt32LE(centralSize, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, ...centrals, end]);
}

const files = listFiles(skillDir).map((path) => ({
  name: ['remcraft-flashcards', ...relative(skillDir, path).split(sep)].join('/'),
  data: readFileSync(path),
}));
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, zip(files));
console.log(`skill: ${files.length} files -> ${relative(root, out)}`);
